# tools/eval.py

import json
import argparse
import re
from typing import Any, List, Dict
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
import sacrebleu
from tqdm import tqdm

# ==================================================
# Evaluate Direction:
# - calculates BLEU and chrF++ scores for a set of
#   hypotheses and references
# ==================================================

def evaluate_direction(name: str, hypotheses: List[str], references: List[str]) -> Dict[str, float]:

  if not hypotheses:
    return {"bleu": 0.0, "chrf++": 0.0}
  
  bleu = sacrebleu.corpus_bleu(hypotheses, [references])
  chrf_pp = sacrebleu.corpus_chrf(hypotheses, [references], word_order=2)
  
  print(f"\n--- Results for {name} ({len(hypotheses)} samples) ---")
  print(f"BLEU:   {bleu.score:.2f}")
  print(f"chrF++: {chrf_pp.score:.2f}")
  
  return {"bleu": bleu.score, "chrf++": chrf_pp.score}

# ==================================================
# Main method:
# - Sets up command-line flag parsing for the model,
#   test file, and output results file name
# ==================================================

def main():
  parser = argparse.ArgumentParser(description="Evaluate merged model on test data generated by inputFormatter")
  parser.add_argument("-m", "--model_path", required=True, help="Path to merged HF model directory")
  parser.add_argument("-t", "--test_file", required=True, help="Path to test JSONL file")
  parser.add_argument("-o", "--output_file", default="eval_results.json", help="Path to save results")
  parser.add_argument("--max_samples", type=int, default=None, help="Optional limit on test samples for quick validation")

  parser.add_argument("--load_in_8bit", action="store_true", help="Load model in 8-bit")
  parser.add_argument("--load_in_4bit", action="store_true", help="Load model in 4-bit")

  args = parser.parse_args()

  print(f"[Kestrel] Loading model and tokenizer from: {args.model_path}")
  tokenizer = AutoTokenizer.from_pretrained(args.model_path)
  
  # ==================================================

  load_kwargs: Dict[str, Any] = {"device_map": "auto"}

  if args.load_in_8bit:
      print("[Kestrel] Loading model in 8-bit precision...")
      load_kwargs["quantization_config"] = BitsAndBytesConfig(load_in_8bit=True)
      load_kwargs["torch_dtype"] = torch.float16
  elif args.load_in_4bit:
      print("[Kestrel] Loading model in 4-bit precision...")
      load_kwargs["quantization_config"] = BitsAndBytesConfig(load_in_4bit=True)
      load_kwargs["torch_dtype"] = torch.float16
  else:
      print("[Kestrel] Loading model in bfloat16 precision...")
      load_kwargs["torch_dtype"] = torch.bfloat16

  model: Any = AutoModelForCausalLM.from_pretrained(
    args.model_path,
    **load_kwargs
  )

  model.eval()

  # ==================================================
  # Load eval dataset
  # ==================================================

  with open(args.test_file, "r", encoding="utf-8") as f:
    data = [json.loads(line) for line in f]

  if args.max_samples:
    data = data[:args.max_samples]

  # ==================================================
  # Containers for results
  # ==================================================

  records: Dict[str, Any] = {}

  # ==================================================
  # Fetch token IDs for stopping generation
  # ==================================================
  
  im_end_id = tokenizer.encode("<|im_end|>")[-1]

  print(f"[Kestrel] Generating translations for {len(data)} test pairs...")

  for item in tqdm(data):
    messages = item["messages"]
    system_text = ""
    user_text = ""
    target_text = ""

    for m in messages:
      if m["role"] == "system":
        system_text = m["content"]
      elif m["role"] == "user":
        user_text = m["content"]
      elif m["role"] == "assistant":
        target_text = m["content"]

    # ==================================================
    # Dynamically identify translation direction
    # ==================================================

    match = re.search(r"Translate the following (.*?) text into (.*?)$", system_text.strip())
    if match:
      src_lang = match.group(1).strip()
      tgt_lang = match.group(2).strip()
    else:
      src_lang = "Source"
      tgt_lang = "Target"

    direction_key = f"{src_lang}_to_{tgt_lang}"
    direction_name = f"{src_lang} -> {tgt_lang}"

    if direction_key not in records:
      records[direction_key] = {"hyp": [], "ref": [], "samples": [], "name": direction_name}

    # ==================================================
    # Reconstruct ChatML prompt
    # ==================================================

    prompt = (
      f"<|im_start|>system\n{system_text}<|im_end|>\n"
      f"<|im_start|>user\n{user_text}<|im_end|>\n"
      f"<|im_start|>assistant\n"
    )
    
    inputs = tokenizer(prompt, return_tensors="pt").to("cuda:0")

    with torch.no_grad():
      output_tokens = model.generate(
        **inputs,
        max_new_tokens=128,
        do_sample=False,              
        pad_token_id=tokenizer.eos_token_id,
        eos_token_id=[tokenizer.eos_token_id, im_end_id]
      )

    # ==================================================
    # Slice input prompt tokens off to isolate model gen
    # ==================================================

    generated_tokens = output_tokens[0][inputs.input_ids.shape[1]:]
    prediction = tokenizer.decode(generated_tokens, skip_special_tokens=True).strip()

    records[direction_key]["hyp"].append(prediction)
    records[direction_key]["ref"].append(target_text)
    records[direction_key]["samples"].append({
      "input": user_text,
      "reference": target_text,
      "prediction": prediction
    })

  # ==================================================
  # Evaluate directions dynamically
  # ==================================================

  directional_scores = {}
  all_hyp = []
  all_ref = []

  for key, data_dict in records.items():
    scores = evaluate_direction(data_dict["name"], data_dict["hyp"], data_dict["ref"])
    directional_scores[key] = scores
    all_hyp.extend(data_dict["hyp"])
    all_ref.extend(data_dict["ref"])

  # ==================================================
  # Aggregate scores across whole set
  # ==================================================

  overall_scores = evaluate_direction("Overall (Bidirectional)", all_hyp, all_ref)

  # ==================================================
  # Save output
  # ==================================================

  final_output = {
    "overall": overall_scores,
    "directions": directional_scores,
    "predictions": {k: v["samples"] for k, v in records.items()}
  }

  with open(args.output_file, "w", encoding="utf-8") as f:
    json.dump(final_output, f, indent=2, ensure_ascii=False)
      
  print(f"\n[Kestrel] Benchmark saved to {args.output_file}")

if __name__ == "__main__":
  main()