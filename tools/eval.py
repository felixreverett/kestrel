# kestrel/tools/eval.py

import json
import argparse
import re
import os
from dataclasses import dataclass
from typing import Any, List, Dict
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
import sacrebleu
from tqdm import tqdm

# ==================================================
# Configs
# 
# [i] An in-memory config is found in Main after the
#     flag parser. If you want to change filepaths,
#     you can do so here.
# ==================================================

@dataclass
class EvalConfig:
  model_path: str
  dataset_path: str
  output_path: str
  max_samples: int
  load_in_8bit: bool = False
  load_in_4bit: bool = False

# ==================================================
# Evaluate Direction:
# - calculates BLEU and chrF++ scores for a set of
#   hypotheses and references
# ==================================================

def evaluate_direction(name: str, hypotheses: List[str], references: List[str]) -> Dict[str, float]:

  if not hypotheses:
    return {"bleu": 0.0, "chrf++": 0.0}
  
  bleu = sacrebleu.corpus_bleu(hypotheses, [references])
  chrf_pp = sacrebleu.corpus_chrf(hypotheses, [references], word_order=2)
  
  print(f"\n--- Results for {name} ({len(hypotheses)} samples) ---")
  print(f"BLEU:   {bleu.score:.2f}")
  print(f"chrF++: {chrf_pp.score:.2f}")
  
  return {"bleu": bleu.score, "chrf++": chrf_pp.score}

# ==================================================
# Save Progress:
# - Enables current progress to be written to disk
#   for safe resumption if interrupted.
# - Saves into `evaluation/` subfolder.
# ==================================================

def save_progress(records: Dict[str, Any], output_file: str):

  directional_scores = {}
  all_hyp = []
  all_ref = []

  for key, data_dict in records.items():
    if data_dict["hyp"]:
      scores = evaluate_direction(data_dict["name"], data_dict["hyp"], data_dict["ref"])
      directional_scores[key] = scores
      all_hyp.extend(data_dict["hyp"])
      all_ref.extend(data_dict["ref"])

  overall_scores = evaluate_direction("Overall (Bidirectional)", all_hyp, all_ref)

  final_output = {
    "overall": overall_scores,
    "directions": directional_scores,
    "predictions": {k: v["samples"] for k, v in records.items()}
  }

  out_dir = os.path.dirname(output_file)
  if out_dir:
    os.makedirs(out_dir, exist_ok=True)

  with open(output_file, "w", encoding="utf-8") as f:
    json.dump(final_output, f, indent=2, ensure_ascii=False)
      
  print(f"\n[Kestrel] Benchmark saved to {output_file}")

# ==================================================
# Main method:
# 1) Sets up command-line flag parsing/config
# 2) Loads into bf16, 8bit, or 4bit mode.
# 3) Loads test file dataset.
# 4) Checks for existing evaluation progress.
# ==================================================

def main():

  parser = argparse.ArgumentParser(description="Evaluate merged model on test data generated by inputFormatter")
  parser.add_argument("-m", "--model_path", required=True, help="Path to merged HF model directory")
  parser.add_argument("-t", "--test_file", required=True, help="Path to test JSONL file")
  parser.add_argument("-o", "--output_file", default="eval_results.json", help="Path to save results")
  parser.add_argument("--max_samples", type=int, default=None, help="Optional limit on test samples for quick validation")

  parser.add_argument("--load_in_8bit", action="store_true", help="Load model in 8-bit")
  parser.add_argument("--load_in_4bit", action="store_true", help="Load model in 4-bit")

  args = parser.parse_args()

  cfg = EvalConfig(
    model_path = f"models/{args.model_path}",
    dataset_path = f"datasets/{args.test_file}",
    output_path = f"evaluation/{args.output_file}",
    max_samples = args.max_samples,
    load_in_8bit=args.load_in_8bit,
    load_in_4bit=args.load_in_4bit
  )

  print(f"[Kestrel] Loading model and tokenizer from: {cfg.model_path}")
  tokenizer = AutoTokenizer.from_pretrained(cfg.model_path)
  
  # ==================================================
  # Load in 8-bit, 4-bit, or bfloat16, + evaluate.
  #
  # [i] I recommend using 8/4 bit for the larger
  #     models, especially on lower-spec devices.
  # ==================================================

  load_kwargs: Dict[str, Any] = {"device_map": "auto"}

  if cfg.load_in_8bit:
      print("[Kestrel] Loading model in 8-bit precision...")
      load_kwargs["quantization_config"] = BitsAndBytesConfig(load_in_8bit=True)
      load_kwargs["torch_dtype"] = torch.float16
  elif cfg.load_in_4bit:
      print("[Kestrel] Loading model in 4-bit precision...")
      load_kwargs["quantization_config"] = BitsAndBytesConfig(load_in_4bit=True)
      load_kwargs["torch_dtype"] = torch.float16
  else:
      print("[Kestrel] Loading model in bfloat16 precision...")
      load_kwargs["torch_dtype"] = torch.bfloat16

  model: Any = AutoModelForCausalLM.from_pretrained(
    cfg.model_path,
    **load_kwargs
  )

  model.eval()

  # ==================================================
  # Load test file dataset
  # - Uses `datasets/` subfolder
  # ==================================================

  with open(cfg.dataset_path, "r", encoding="utf-8") as f:
    data = [json.loads(line) for line in f]

  if cfg.max_samples:
    data = data[:cfg.max_samples]

  # ==================================================
  # Check for existing evaluation progress
  # ==================================================

  records: Dict[str, Any] = {}
  processed_count = 0

  if os.path.exists(cfg.output_path):
    print(f"\n[Kestrel] Loading existing output file '{cfg.output_path}'.")
    with open(cfg.output_path, "r", encoding="utf-8") as f:
      existing_data = json.load(f)
      
      if "predictions" in existing_data:
        for dir_key, samples in existing_data["predictions"].items():
          langs = dir_key.split("_to_")
          dir_name = f"{langs[0]} -> {langs[1]}" if len(langs) == 2 else dir_key
          
          records[dir_key] = {
            "hyp": [s["prediction"] for s in samples],
            "ref": [s["reference"] for s in samples],
            "samples": samples,
            "name": dir_name
          }
          processed_count += len(samples)
    
    print(f"[Kestrel] Skipping first {processed_count} samples.")

  data_to_process = data[processed_count:]

  if not data_to_process:
    print("[Kestrel] All samples already evaluated. Exiting program.")
    return

  # ==================================================
  # Fetch token IDs for stopping generation
  # ==================================================
  
  im_end_id = tokenizer.encode("<|im_end|>")[-1]

  print(f"[Kestrel] Generating translations for {len(data_to_process)} test pairs...")

  try:
    for item in tqdm(data_to_process):
      messages = item["messages"]
      system_text = ""
      user_text = ""
      target_text = ""

      for m in messages:
        if m["role"] == "system":
          system_text = m["content"]
        elif m["role"] == "user":
          user_text = m["content"]
        elif m["role"] == "assistant":
          target_text = m["content"]

      # ==================================================
      # Dynamically get translation direction
      # ==================================================

      match_en = re.search(r"Translate the following (.*?) text into (.*?)$", system_text.strip())
      match_fr = re.search(r"Traduisez le texte (.*?) suivant en (.*?)\.$", system_text.strip())
      
      if match_en:
        src_lang = match_en.group(1).strip()
        tgt_lang = match_en.group(2).strip()
      elif match_fr:
        src_lang = match_fr.group(1).strip()
        tgt_lang = match_fr.group(2).strip()
      else:
        src_lang = "Source"
        tgt_lang = "Target"

      direction_key = f"{src_lang}_to_{tgt_lang}"
      direction_name = f"{src_lang} -> {tgt_lang}"

      if direction_key not in records:
        records[direction_key] = {"hyp": [], "ref": [], "samples": [], "name": direction_name}
      
      # ==================================================
      # Reconstruct ChatML prompt
      # ==================================================

      prompt = (
        f"<|im_start|>system\n{system_text}<|im_end|>\n"
        f"<|im_start|>user\n{user_text}<|im_end|>\n"
        f"<|im_start|>assistant\n"
      )
      
      inputs = tokenizer(prompt, return_tensors="pt").to("cuda:0")

      with torch.no_grad():
        output_tokens = model.generate(
          **inputs,
          max_new_tokens=128,
          do_sample=False,              
          pad_token_id=tokenizer.eos_token_id,
          eos_token_id=[tokenizer.eos_token_id, im_end_id]
        )

      # ==================================================
      # Slice input prompt tokens off to isolate model gen
      # ==================================================

      generated_tokens = output_tokens[0][inputs.input_ids.shape[1]:]
      prediction = tokenizer.decode(generated_tokens, skip_special_tokens=True).strip()

      records[direction_key]["hyp"].append(prediction)
      records[direction_key]["ref"].append(target_text)
      records[direction_key]["samples"].append({
        "input": user_text,
        "reference": target_text,
        "prediction": prediction
      })

      if len(records[direction_key]["samples"]) % 50 == 0:
          save_progress(records, cfg.output_path)

  except KeyboardInterrupt:
    print("\n[Kestrel] Interrupted by user. Saving progress before exiting...")

  finally:
    save_progress(records, cfg.output_path)

if __name__ == "__main__":
  main()